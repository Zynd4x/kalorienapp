export function searchLocalFoods(query: string): Food[] {
  const value = query.trim().toLowerCase();
  if (!value) return [];
  return localFoods.filter(
    (food) =>
      food.name.toLowerCase().includes(value) ||
      (food.brand ?? '').toLowerCase().includes(value),
  );
}
